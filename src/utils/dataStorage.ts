  // Download report as separate CSV file (original functionality)
  static downloadReportAsCSV(data: unknown, filename: string): void {
    // Convert report object to CSV format
    const csvData = [];
    
    // Add report metadata
    const dataObj = data as Record<string, unknown>;
    csvData.push({
      'Report Type': (dataObj.reportType as string) || 'Unknown',
      'Entity Type': (dataObj.entityType as string) || 'All',
      'Date Range Start': (dataObj.dateRange as { start?: string })?.start ? new Date((dataObj.dateRange as { start?: string }).start!).toLocaleDateString() : '',
      'Date Range End': (dataObj.dateRange as { end?: string })?.end ? new Date((dataObj.dateRange as { end?: string }).end!).toLocaleDateString() : '',
      'Generated At': new Date().toLocaleString()
    });
    
    // Add empty row
    csvData.push({});
    
    // Add employee hours data if available
    if (dataObj.employeeHours && Object.keys(dataObj.employeeHours as Record<string, unknown>).length > 0) {
      csvData.push({ 'Section': 'Employee Hours Summary' });
      Object.entries(dataObj.employeeHours as Record<string, unknown>).forEach(([employeeId, hours]: [string, unknown]) => {
        csvData.push({
          'Employee ID': employeeId,
          'Regular Hours': hours.regular,
          'Overtime Hours': hours.overtime,
          'Total Hours': hours.total,
          'Shifts': hours.shifts
        });
      });
      csvData.push({});
    }
    
    // Add equipment usage data if available
    if (data.equipmentUsage && Object.keys(data.equipmentUsage).length > 0) {
      csvData.push({ 'Section': 'Equipment Usage Summary' });
      Object.entries(data.equipmentUsage).forEach(([equipmentId, usage]: [string, any]) => {
        csvData.push({
          'Equipment ID': equipmentId,
          'Total Hours': usage.totalHours,
          'Sessions': usage.sessions
        });
      });
      csvData.push({});
    }
    
    // Add material movement data if available
    if (data.materialMovement && Object.keys(data.materialMovement).length > 0) {
      csvData.push({ 'Section': 'Material Movement Summary' });
      Object.entries(data.materialMovement).forEach(([materialId, movement]: [string, any]) => {
        csvData.push({
          'Material ID': materialId,
          'Received': movement.received,
          'Issued': movement.issued,
          'Net Movement': movement.net
        });
      });
      csvData.push({});
    }
    
    // Add activity logs if available
    if (data.logs && data.logs.length > 0) {
      csvData.push({ 'Section': 'Activity Logs' });
      data.logs.forEach((log: any) => {
        csvData.push({
          'Log ID': log.id,
          'Entity ID': log.entityId,
          'Entity Type': log.entityType,
          'Action': log.action,
          'Timestamp': new Date(log.timestamp).toLocaleString(),
          'Site': log.site,
          'Notes': log.notes || '',
          'Quantity': log.quantity || ''
        });
      });
    }
    
    this.downloadCSV(csvData, filename);
  }

