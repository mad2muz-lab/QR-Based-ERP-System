  // Save data to localStorage as CSV
  static saveToCSV<T>(key: string, data: T[]): void {
    try {
      const csv = Papa.unparse(data);
      localStorage.setItem(key, csv);
    } catch (error) {
      console.error(`Error saving ${key} to CSV:`, error);
    }
  }

  // Load data from localStorage CSV
  static loadFromCSV<T>(key: string): T[] {
    try {
      const csv = localStorage.getItem(key);
      if (!csv) return [];
      
      const result = Papa.parse(csv, { 
        header: true,
        dynamicTyping: true,
        skipEmptyLines: true
      });
      return result.data as T[];
    } catch (error) {
      console.error(`Error loading ${key} from CSV:`, error);
      return [];
    }
  }

  // Download CSV file
  static downloadCSV(data: unknown[], filename: string): void {
    const csv = Papa.unparse(data);
    const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.setAttribute('href', url);
    link.setAttribute('download', filename);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

