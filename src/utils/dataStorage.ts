  static loadSites(): Site[] {
    const sites = this.loadFromCSV<Site>(this.STORAGE_KEYS.sites);
    console.log(`Sites loaded from storage: ${sites.length} sites`);

    // Process and fix site coordinates
    const processedSites = sites.map(site => {
      let coordinates: [number, number] = [0, 0];
      
      try {
        // Handle different coordinate formats
        if (site.coordinates) {
          // Case 1: Already an array of numbers
          if (Array.isArray(site.coordinates) && 
              typeof site.coordinates[0] === 'number' && 
              typeof site.coordinates[1] === 'number') {
            coordinates = [site.coordinates[0], site.coordinates[1]];
          }
          // Case 2: Array of strings
          else if (Array.isArray(site.coordinates)) {
            coordinates = [
              parseFloat(String(site.coordinates[0])), 
              parseFloat(String(site.coordinates[1]))
            ];
          }
          // Case 3: String in format "lng,lat"
          else if (typeof site.coordinates === 'string' && (site.coordinates as string).includes(',')) {
            const parts = (site.coordinates as string).split(',').map((part: string) => parseFloat(part.trim()));
            if (parts.length === 2 && !isNaN(parts[0]) && !isNaN(parts[1])) {
              coordinates = [parts[0], parts[1]];
            }
          }
          // Case 4: String in format "lat lng"
          else if (typeof site.coordinates === 'string' && (site.coordinates as string).includes(' ')) {
            const parts = (site.coordinates as string).split(' ').map((part: string) => parseFloat(part.trim()));
            if (parts.length === 2 && !isNaN(parts[0]) && !isNaN(parts[1])) {
              coordinates = [parts[1], parts[0]]; // Note: swapping to [lng, lat]
            }
          }
        }
        
        // Validate coordinates
        if (isNaN(coordinates[0]) || isNaN(coordinates[1]) ||
            coordinates[0] === 0 || coordinates[1] === 0) {
          console.warn(`Site ${site.id} has invalid coordinates, using default:`, site.coordinates);
          // Default to Riyadh coordinates
          coordinates = [46.6753, 24.7136];
        }
      } catch (error) {
        console.error(`Error processing coordinates for site ${site.id}:`, error);
        coordinates = [46.6753, 24.7136]; // Default to Riyadh
      }
      
      return {
        ...site,
        coordinates
      };
    });

    // Log coordinate processing results
    console.log(`Sites after coordinate processing: ${processedSites.length} sites`);
    if (processedSites.length > 0) {
      console.log("Sample processed site:", JSON.stringify(processedSites[0]));
    }
    
    return processedSites;
  }

