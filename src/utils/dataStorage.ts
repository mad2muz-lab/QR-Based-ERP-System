  // Save report data to Logs.csv with append functionality
  static saveReportToLogsCSV(data: unknown): void {
    try {
      // Create log entry for this report
      const dataObj = data as Record<string, unknown>;
      const logEntry = {
        'Timestamp': new Date().toISOString(),
        'Report Type': (dataObj.reportType as string) || 'Unknown',
        'Entity Type': (dataObj.entityType as string) || 'All',
        'Date Range Start': (dataObj.dateRange as { start?: string })?.start ? new Date((dataObj.dateRange as { start?: string }).start!).toISOString() : '',
        'Date Range End': (dataObj.dateRange as { end?: string })?.end ? new Date((dataObj.dateRange as { end?: string }).end!).toISOString() : '',
        'Generated By': this.getCurrentUserId() || 'System',
        'Employee Records': dataObj.employeeHours ? Object.keys(dataObj.employeeHours as Record<string, unknown>).length : 0,
        'Equipment Records': dataObj.equipmentUsage ? Object.keys(dataObj.equipmentUsage as Record<string, unknown>).length : 0,
        'Material Records': dataObj.materialMovement ? Object.keys(dataObj.materialMovement as Record<string, unknown>).length : 0,
        'Activity Logs': dataObj.logs ? (dataObj.logs as unknown[]).length : 0,
        'Total Records': (dataObj.logs ? (dataObj.logs as unknown[]).length : 0) + 
                        (dataObj.employeeHours ? Object.keys(dataObj.employeeHours as Record<string, unknown>).length : 0) +
                        (dataObj.equipmentUsage ? Object.keys(dataObj.equipmentUsage as Record<string, unknown>).length : 0) +
                        (dataObj.materialMovement ? Object.keys(dataObj.materialMovement as Record<string, unknown>).length : 0)
      };

      // Load existing logs
      const existingLogs = this.loadLogsCSV();
      
      // Append new log entry
      existingLogs.push(logEntry);
      
      // Save back to Logs.csv
      this.saveLogsCSV(existingLogs);
      
      console.log('Report logged to Logs.csv successfully');
    } catch (error) {
      console.error('Failed to save report to Logs.csv:', error);
    }
  }

