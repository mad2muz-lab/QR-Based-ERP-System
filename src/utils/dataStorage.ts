  // Transaction Logging
  static logTransaction(entityType: string, action: 'create' | 'update' | 'delete', data: any): void {
    const logs = this.loadTransactionLogs();
    const newLog: TransactionLog = {
      id: `txn-${Date.now()}`,
      entityType,
      action,
      entityId: data.id,
      data,
      timestamp: new Date().toISOString(),
      userId: this.getCurrentUserId()
    };
    
    logs.push(newLog);
    this.saveTransactionLogs(logs);
  }

  private static loadTransactionLogs(): TransactionLog[] {
    return this.loadFromCSV<TransactionLog>(this.STORAGE_KEYS.transactionLog);
  }

